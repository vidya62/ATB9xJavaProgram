package Oct.ex_15102024_Increment_Decrement;

public class Lab070 {
    public static void main(String[] args) {
        int a=10;
        int res_post = a--;
        int res_pre = --a;
        System.out.println(res_post);
        System.out.println(res_pre);
        System.out.println(a);
    }
}
